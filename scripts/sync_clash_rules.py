#!/usr/bin/env python3
"""Generate Clash classical providers and Surge rulesets from Egern domain lists.

Supports the simple YAML subset used here: supported set headers, unquoted
domain/keyword list entries, blank lines and full-line comments. Unsupported
syntax fails instead of silently losing rules. No third-party dependencies.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TYPES = {
    "domain_keyword_set": "DOMAIN-KEYWORD",
    "domain_suffix_set": "DOMAIN-SUFFIX",
    "domain_set": "DOMAIN",
}

CLASH_TARGETS = (
    "custom-direct",
    "custom-proxy",
    "gemini",
    "claude",
    "openai",
    "grok",
    "apple-ai",
    "ai",
)

SURGE_TARGETS = (
    "custom-direct",
    "custom-proxy",
    "ourbit",
    "meta",
    "gemini",
    "claude",
    "openai",
    "grok",
    "apple-ai",
    "ai",
)

# Surge-only extra rules (e.g. URL-REGEX supported natively by Surge RULE-SET)
SURGE_EXTRAS = {
    "gemini": [
        r"URL-REGEX,https://www\.google\.com/.*continue=https://gemini\.google\.com.+",
    ],
    "ai": [
        r"URL-REGEX,https://www\.google\.com/.*continue=https://gemini\.google\.com.+",
    ],
}


def parse_egern(source: Path) -> list[str]:
    entries = []
    current = None
    seen = set()
    for number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.endswith(":") and line[:-1] in TYPES:
            current = line[:-1]
            if current in seen:
                raise ValueError(f"{source}:{number}: duplicate set {current}")
            seen.add(current)
        elif current and re.fullmatch(r"- +[A-Za-z0-9_.-]+", line):
            entries.append(f"{TYPES[current]},{line.split(None, 1)[1]}")
        else:
            raise ValueError(f"{source}:{number}: unsupported syntax: {line}")
    if not entries:
        raise ValueError(f"{source}: empty rule set")
    if len(entries) != len(set(entries)):
        raise ValueError(f"{source}: duplicate rules")
    return entries


def render_clash(source: Path) -> str:
    entries = parse_egern(source)
    return (
        "# Generated by scripts/sync_clash_rules.py; edit the Egern source.\n"
        "payload:\n" + "".join(f"  - {entry}\n" for entry in entries)
    )


def render_surge(source: Path, name: str) -> str:
    entries = parse_egern(source) + SURGE_EXTRAS.get(name, [])
    return (
        "# Generated by scripts/sync_clash_rules.py; edit the Egern source.\n"
        + "".join(f"{entry}\n" for entry in entries)
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    outputs = {}
    for name in CLASH_TARGETS:
        src = ROOT / f"egern/rules/{name}.yaml"
        outputs[ROOT / f"clash/rules/{name}.yaml"] = render_clash(src)
    for name in SURGE_TARGETS:
        src = ROOT / f"egern/rules/{name}.yaml"
        outputs[ROOT / f"surge/rules/{name}.list"] = render_surge(src, name)

    stale = []
    for target, content in outputs.items():
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            print(f"Generated {target.relative_to(ROOT)}")
    if stale:
        print("Out of sync: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
